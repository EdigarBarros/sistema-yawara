let seq = 0;
const tid = () => `tsk-seed-${++seq}`;

function task(
  clock: Clock,
  title: string,
  departmentId: string,
  status: TaskStatus,
  dueIn: number | undefined,
  responsibleId?: string,
  description?: string,
): EventTask {
  const at = clock.at(-10);
  return {
    id: tid(),
    title,
    description,
    departmentId,
    status,
    dueDate: dueIn === undefined ? undefined : clock.date(dueIn),
    responsibleId,
    createdAt: at,
    updatedAt: at,
  };
}

function schedule(items: [string, string, string?][]): ScheduleItem[] {
  return items.map(([time, title, description]) => ({ id: tid(), time, title, description }));
}

function suppliers(items: [string, string, Supplier["status"], string?][]): Supplier[] {
  return items.map(([name, service, status, contact]) => ({ id: tid(), name, service, status, contact }));
}

